int main(void){
    for (int x = 0; x < 24; x++){
        for(int y = 0; y < 24; y++){

            unsigned char value = board[x][y];
            struct pixel p; 
            *(unsigned char*)&p = value;
            char format[32] = {0};
            
            if (p.visible == 0) {
                sprintf(format, "  ");
                printf("%s", format);
                continue;
            }

            int fg_code;
            switch(p.color) {
                case 1: fg_code = 31; break; // Red
                case 2: fg_code = 32; break; // Green
                case 3: fg_code = 33; break; // Yellow
                case 4: fg_code = 34; break; // Blue
                default: fg_code = 37;       // White
            }

            int bg_code;
            switch(p.background) {
                case 1: bg_code = 44; break; // Blue background
                default: bg_code = 40;       // Black background
            }

            char character;
            switch(p.symbol) {
                case 1: character = '#'; break;
                case 2: character = '@'; break;
                case 3: character = '*'; break;
                case 4: character = 'O'; break;
                default: character = '?';
            }

            sprintf(format, "\033[5;1;%d;%dm%c \033[0m", bg_code, fg_code, character);

            printf("%s", format);
        }
        printf("\n");
    }
}